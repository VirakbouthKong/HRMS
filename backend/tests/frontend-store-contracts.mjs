// Tests the real frontend store in Node with controlled API doubles; no browser automation.
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../../frontend/',import.meta.url));
const require=createRequire(path.join(root,'package.json'));
const {build}=require('esbuild');
const folder=path.join(root,'node_modules','.cache','hrms-verification');
fs.mkdirSync(folder,{recursive:true});
const compiled=path.join(folder,'store.cjs');
await build({stdin:{contents:"export { useHrmsStore } from './src/store/useHrmsStore'; export { payrollApi,attendanceApi,attendanceRequestApi,employeeApi } from './src/api';",resolveDir:root,loader:'ts'},bundle:true,platform:'node',format:'cjs',outfile:compiled,define:{'import.meta.env':'{}'},logLevel:'silent'});
const {useHrmsStore:store,payrollApi,attendanceApi,attendanceRequestApi,employeeApi}=require(compiled);
const results=[];
function check(name,passed,detail){results.push({name,passed,detail});console.log(`${passed?'PASS':'FAIL'} ${name}: ${detail}`);}
const serverPayroll={payrollId:1,employeeId:1,baseSalary:1500,netSalary:1500,period:'2026-11',generatedDate:'2026-11-13'};
payrollApi.getAll=async()=>[serverPayroll];
payrollApi.markPaid=async()=>{serverPayroll.status='PAID';serverPayroll.paidDate='2026-11-13';return serverPayroll;};
store.setState({employees:[],payroll:[{recordId:1,status:'PROCESSED'}]});
await store.getState().markPayrollPaid(1);
const before=store.getState().payroll[0].status;
await store.getState().fetchPayrollByPeriod('2026-11');
const after=store.getState().payroll[0].status;
check('Mark paid survives API refresh',after==='PAID',`${before} -> ${after}`);
const request={attendanceId:1,employeeId:1,employeeName:'QA',attendanceDate:'2026-11-13',requestedCheckIn:'08:00',requestedCheckOut:'17:00',reason:'QA correction'};
let calls=0;
attendanceRequestApi.submit=async()=>{calls++;throw new Error('Simulated server failure');};
store.setState({currentUser:{role:'ROLE_EMPLOYEE'},attendanceCorrections:[],pendingActions:[]});
const employeeResult=await store.getState().requestAttendanceCorrection(request);
check('Employee correction request reaches server',calls>0,`success=${employeeResult.success}; API calls=${calls}`);
store.setState({currentUser:{role:'ROLE_HR',fullName:'QA manager'},attendanceCorrections:[],pendingActions:[]});
const managerResult=await store.getState().requestAttendanceCorrection(request);
check('Correction submission reports API failure',managerResult.success===false,`success=${managerResult.success}; API rejected`);
const id=1;
attendanceRequestApi.review=async()=>{throw new Error('Simulated server failure');};
const approval=await store.getState().reviewAttendanceCorrection(id,'APPROVED');
check('Correction approval reports API failure',approval.success===false,`success=${approval.success}; API rejected`);
let requestedStatus;
employeeApi.updateStatus=async(id,status)=>{requestedStatus=status;return {};};
store.setState({employees:[{employeeId:1,departmentId:1}],departments:[]});
await store.getState().deleteEmployee(1);
check('Terminate employee sends supported backend status',['ACTIVE','INACTIVE'].includes(requestedStatus),`sent ${requestedStatus}; backend supports ACTIVE/INACTIVE`);
fs.writeFileSync(new URL('./frontend-store-contracts-results.json',import.meta.url),JSON.stringify(results,null,2));
process.exitCode=results.some(r=>!r.passed)?1:0;
