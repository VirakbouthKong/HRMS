CREATE TABLE tbl_attendance_request (
    correction_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_id integer NOT NULL REFERENCES tbl_attendance(attendance_id),
    employee_id integer NOT NULL REFERENCES tbl_employee(employee_id),
    requested_check_in timestamp NOT NULL,
    requested_check_out timestamp,
    original_check_in timestamp,
    original_check_out timestamp,
    reason varchar(500) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    requested_at timestamp NOT NULL,
    reviewed_by integer REFERENCES tbl_employee(employee_id),
    reviewed_by_name varchar(255),
    reviewed_at timestamp,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT chk_request_time_order CHECK (requested_check_out IS NULL OR requested_check_out >= requested_check_in)
);
CREATE UNIQUE INDEX uq_attendance_pending_request ON tbl_attendance_request(attendance_id) WHERE status='PENDING';
