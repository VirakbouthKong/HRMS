-- Module: the everyday things an HRMS is actually used for, plus a trail of who changed what.
--
--   tbl_announcement      the notice board
--   tbl_employee_document contracts, IDs and certificates, with an expiry date
--   tbl_asset             company property, and who currently holds it
--   tbl_asset_assignment  the handover history of each asset
--   tbl_expense_claim     money an employee spent and wants back
--   tbl_audit_log         every change that went through the API
--
-- Document and receipt bytes live in the database (bytea), the same way profile photos already do
-- in the Auth service. That keeps a deployment to "a JAR and a database" with no shared volume.

CREATE TABLE IF NOT EXISTS tbl_announcement (
    announcement_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           varchar(200)  NOT NULL,
    body            varchar(5000) NOT NULL,
    -- ALL, DEPARTMENT or ROLE
    audience        varchar(20)   NOT NULL DEFAULT 'ALL',
    -- set when audience = DEPARTMENT
    department_id   integer,
    -- set when audience = ROLE: ADMIN, HR_MANAGER, HR_STAFF or EMPLOYEE
    audience_role   varchar(20),
    -- GENERAL, POLICY, EVENT, URGENT, CELEBRATION
    category        varchar(20)   NOT NULL DEFAULT 'GENERAL',
    pinned          boolean       NOT NULL DEFAULT false,
    published_on    date,
    expires_on      date,
    -- DRAFT, PUBLISHED, ARCHIVED
    status          varchar(20)   NOT NULL DEFAULT 'DRAFT',
    author_id       integer,
    created_on      timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tbl_announcement_department FOREIGN KEY (department_id) REFERENCES tbl_department (department_id),
    CONSTRAINT fk_tbl_announcement_author FOREIGN KEY (author_id) REFERENCES tbl_employee (employee_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_announcement_status ON tbl_announcement (status, pinned);

CREATE TABLE IF NOT EXISTS tbl_employee_document (
    document_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   integer      NOT NULL,
    -- CONTRACT, ID_CARD, PASSPORT, VISA, WORK_PERMIT, CERTIFICATE, CV, APPRAISAL, MEDICAL, OTHER
    doc_type      varchar(30)  NOT NULL DEFAULT 'OTHER',
    title         varchar(200) NOT NULL,
    file_name     varchar(255) NOT NULL,
    content_type  varchar(100) NOT NULL,
    size_bytes    integer      NOT NULL,
    content       bytea        NOT NULL,
    issued_on     date,
    -- what the expiring-documents report looks at
    expires_on    date,
    uploaded_by   integer,
    uploaded_at   timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes         varchar(500),
    CONSTRAINT ck_tbl_employee_document_size CHECK (size_bytes > 0),
    CONSTRAINT fk_tbl_employee_document_employee FOREIGN KEY (employee_id) REFERENCES tbl_employee (employee_id),
    CONSTRAINT fk_tbl_employee_document_uploader FOREIGN KEY (uploaded_by) REFERENCES tbl_employee (employee_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_employee_document_employee ON tbl_employee_document (employee_id);
CREATE INDEX IF NOT EXISTS ix_tbl_employee_document_expiry ON tbl_employee_document (expires_on);

CREATE TABLE IF NOT EXISTS tbl_asset (
    asset_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_tag      varchar(40)  NOT NULL,
    name           varchar(150) NOT NULL,
    -- LAPTOP, DESKTOP, MONITOR, PHONE, VEHICLE, FURNITURE, ACCESS_CARD, TOOL, OTHER
    category       varchar(30)  NOT NULL DEFAULT 'OTHER',
    serial_number  varchar(100),
    purchase_date  date,
    purchase_cost  numeric(10, 2),
    -- NEW, GOOD, FAIR, POOR, DAMAGED
    condition_note varchar(20)  NOT NULL DEFAULT 'GOOD',
    -- IN_STOCK, ASSIGNED, MAINTENANCE, RETIRED, LOST
    status         varchar(20)  NOT NULL DEFAULT 'IN_STOCK',
    -- who holds it right now; NULL while it is in stock
    assigned_to    integer,
    assigned_on    date,
    notes          varchar(500),
    CONSTRAINT uq_tbl_asset_tag UNIQUE (asset_tag),
    CONSTRAINT fk_tbl_asset_employee FOREIGN KEY (assigned_to) REFERENCES tbl_employee (employee_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_asset_status ON tbl_asset (status);
CREATE INDEX IF NOT EXISTS ix_tbl_asset_assigned ON tbl_asset (assigned_to);

-- Every handover, so "who had this laptop in March" has an answer.
CREATE TABLE IF NOT EXISTS tbl_asset_assignment (
    assignment_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id         integer NOT NULL,
    employee_id      integer NOT NULL,
    assigned_on      date    NOT NULL DEFAULT CURRENT_DATE,
    returned_on      date,
    condition_out    varchar(20),
    condition_back   varchar(20),
    assigned_by      integer,
    notes            varchar(500),
    CONSTRAINT fk_tbl_asset_assignment_asset FOREIGN KEY (asset_id) REFERENCES tbl_asset (asset_id),
    CONSTRAINT fk_tbl_asset_assignment_employee FOREIGN KEY (employee_id) REFERENCES tbl_employee (employee_id),
    CONSTRAINT fk_tbl_asset_assignment_by FOREIGN KEY (assigned_by) REFERENCES tbl_employee (employee_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_asset_assignment_asset ON tbl_asset_assignment (asset_id);

CREATE TABLE IF NOT EXISTS tbl_expense_claim (
    claim_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference        varchar(20)   NOT NULL,
    employee_id      integer       NOT NULL,
    -- TRAVEL, ACCOMMODATION, MEALS, TRAINING, EQUIPMENT, MEDICAL, OTHER
    category         varchar(30)   NOT NULL DEFAULT 'OTHER',
    amount           numeric(10, 2) NOT NULL,
    currency         varchar(3)    NOT NULL DEFAULT 'USD',
    incurred_on      date          NOT NULL,
    description      varchar(500)  NOT NULL,
    -- DRAFT, SUBMITTED, APPROVED, REJECTED, PAID
    status           varchar(20)   NOT NULL DEFAULT 'DRAFT',
    submitted_on     date,
    decided_by       integer,
    decided_on       date,
    decision_remark  varchar(255),
    paid_on          date,
    -- the receipt, where one was attached
    receipt_name     varchar(255),
    receipt_type     varchar(100),
    receipt_size     integer,
    receipt_content  bytea,
    CONSTRAINT uq_tbl_expense_claim_reference UNIQUE (reference),
    CONSTRAINT ck_tbl_expense_claim_amount CHECK (amount > 0),
    CONSTRAINT fk_tbl_expense_claim_employee FOREIGN KEY (employee_id) REFERENCES tbl_employee (employee_id),
    CONSTRAINT fk_tbl_expense_claim_decided_by FOREIGN KEY (decided_by) REFERENCES tbl_employee (employee_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_expense_claim_employee ON tbl_expense_claim (employee_id, status);

-- Who changed what, written automatically for every request that is not a GET.
CREATE TABLE IF NOT EXISTS tbl_audit_log (
    audit_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at            timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- the account id from the token subject, and the employee behind it where there is one
    account_id    integer,
    user_name     varchar(100),
    employee_id   integer,
    roles         varchar(120),
    -- POST, PUT, PATCH, DELETE
    method        varchar(10)  NOT NULL,
    path          varchar(300) NOT NULL,
    -- the area of the system, worked out from the path: EMPLOYEE, LEAVE, PAYROLL, ...
    area          varchar(40),
    status_code   integer      NOT NULL,
    -- how long the request took, in milliseconds
    duration_ms   integer,
    client_ip     varchar(60),
    -- the error message when the request failed
    detail        varchar(500),
    CONSTRAINT fk_tbl_audit_log_employee FOREIGN KEY (employee_id) REFERENCES tbl_employee (employee_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_audit_log_at ON tbl_audit_log (at DESC);
CREATE INDEX IF NOT EXISTS ix_tbl_audit_log_account ON tbl_audit_log (account_id);
CREATE INDEX IF NOT EXISTS ix_tbl_audit_log_area ON tbl_audit_log (area);

