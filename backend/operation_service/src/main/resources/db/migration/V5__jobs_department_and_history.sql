-- Jobs belong to a department, an employee's job must be in their own department, and job changes
-- are recorded in tbl_jobhistory. Stops with an error instead of guessing if the data is not as expected.

-- 1. Each job gets a department.
ALTER TABLE tbl_job ADD COLUMN department_id integer;
ALTER TABLE tbl_job ADD CONSTRAINT fk_tbl_job_department
    FOREIGN KEY (department_id) REFERENCES tbl_department (department_id);

-- tbl_job rows were inserted with explicit ids: move the id sequence past them.
SELECT setval(pg_get_serial_sequence('tbl_job', 'job_id'), (SELECT max(job_id) FROM tbl_job));

-- New job for the manager of the operation department.
INSERT INTO tbl_job (job_title, description, department_id)
SELECT 'Operation Manager', 'Leader of Operation Department', d.department_id
FROM tbl_department d WHERE d.department_name = 'OPERATION DEPARTMENT';

UPDATE tbl_job j SET department_id = d.department_id
FROM tbl_department d
WHERE d.department_name = CASE trim(j.job_title)
        WHEN 'IT Manager' THEN 'IT DEPARTMENT'
        WHEN 'FrontEnd Developer' THEN 'IT DEPARTMENT'
        WHEN 'IT Tester' THEN 'IT DEPARTMENT'
        WHEN 'BackEnd Developer' THEN 'IT DEPARTMENT'
        WHEN 'UX/UI Designer' THEN 'IT DEPARTMENT'
        WHEN 'Software Engineering' THEN 'IT DEPARTMENT'
        WHEN 'IT Staff' THEN 'CYBERSECURITY DEPARTMENT'
        WHEN 'Cyber Manager' THEN 'CYBERSECURITY DEPARTMENT'
        WHEN 'Cybersecurity Staff' THEN 'CYBERSECURITY DEPARTMENT'
        WHEN 'Outdoor Saler' THEN 'SALE DEPARTMENT'
        WHEN 'Indoor Saler' THEN 'SALE DEPARTMENT'
        WHEN 'Marketer' THEN 'SALE DEPARTMENT'
        WHEN 'Content Creator' THEN 'SALE DEPARTMENT'
        WHEN 'Sale Manager' THEN 'SALE DEPARTMENT'
        WHEN 'Accounting Staff' THEN 'FINANCE DEPARTMENT'
        WHEN 'Finance Staff' THEN 'FINANCE DEPARTMENT'
        WHEN 'Finance Manager' THEN 'FINANCE DEPARTMENT'
        WHEN 'Worker' THEN 'OPERATION DEPARTMENT'
        WHEN 'Team Lead Worker' THEN 'OPERATION DEPARTMENT'
        WHEN 'Operation Manager' THEN 'OPERATION DEPARTMENT'
        WHEN 'HR Staff' THEN 'HR DEPARTMENT'
        WHEN 'HR Manager' THEN 'HR DEPARTMENT'
        WHEN 'CEO' THEN 'LEADER DEPARTMENT'
    END;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM tbl_job WHERE department_id IS NULL) THEN
        RAISE EXCEPTION 'V5: these jobs have no department mapping: %',
            (SELECT string_agg(trim(job_title), ', ') FROM tbl_job WHERE department_id IS NULL);
    END IF;
END $$;

ALTER TABLE tbl_job ALTER COLUMN department_id SET NOT NULL;

-- 2. Job history ids are generated from now on.
ALTER TABLE tbl_jobhistory ALTER COLUMN jobhistory_id ADD GENERATED BY DEFAULT AS IDENTITY;

-- 3. The HR Manager working in the operation department becomes Operation Manager (recorded in history).
DO $$
DECLARE
    moved integer;
    hr_manager integer := (SELECT job_id FROM tbl_job WHERE trim(job_title) = 'HR Manager');
    op_manager integer := (SELECT job_id FROM tbl_job WHERE job_title = 'Operation Manager');
BEGIN
    IF (SELECT count(*) FROM tbl_employee e JOIN tbl_department d ON d.department_id = e.department_id
        WHERE e.job_id = hr_manager AND d.department_name = 'OPERATION DEPARTMENT') <> 1 THEN
        RAISE EXCEPTION 'V5: expected exactly one HR Manager in OPERATION DEPARTMENT';
    END IF;
    SELECT e.employee_id INTO moved FROM tbl_employee e JOIN tbl_department d ON d.department_id = e.department_id
    WHERE e.job_id = hr_manager AND d.department_name = 'OPERATION DEPARTMENT';

    INSERT INTO tbl_jobhistory (employee_id, job_id, started_date, end_date, remark)
    VALUES (moved, hr_manager, CURRENT_DATE, CURRENT_DATE, 'Starting record'),
           (moved, op_manager, CURRENT_DATE, NULL, 'Job title corrected for department rule');
    UPDATE tbl_employee SET job_id = op_manager WHERE employee_id = moved;
END $$;

-- 4. Everyone else starts their history with their current job.
INSERT INTO tbl_jobhistory (employee_id, job_id, started_date, end_date, remark)
SELECT e.employee_id, e.job_id, CURRENT_DATE, NULL, 'Starting record'
FROM tbl_employee e
WHERE e.job_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM tbl_jobhistory h WHERE h.employee_id = e.employee_id);

-- 5. Every employee's job must now be in their own department.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM tbl_employee e JOIN tbl_job j ON j.job_id = e.job_id
               WHERE j.department_id <> e.department_id) THEN
        RAISE EXCEPTION 'V5: employees whose job is in another department: %',
            (SELECT string_agg(e.employee_id::text, ', ') FROM tbl_employee e JOIN tbl_job j ON j.job_id = e.job_id
             WHERE j.department_id <> e.department_id);
    END IF;
END $$;
