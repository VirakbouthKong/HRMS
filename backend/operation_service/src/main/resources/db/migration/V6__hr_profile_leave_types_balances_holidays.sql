/* ------------------------------------------------------------------ 4. leave: new columns */

ALTER TABLE tbl_leave
    ADD COLUMN IF NOT EXISTS leave_type_id   integer,
    -- working days this request costs (weekends and public holidays already removed); 0.5 for a half day
    ADD COLUMN IF NOT EXISTS day_portion     numeric(5, 1),
    ADD COLUMN IF NOT EXISTS half_day        boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS half_day_period varchar(10),
    ADD COLUMN IF NOT EXISTS submitted_on    date,
    ADD COLUMN IF NOT EXISTS decided_on      date,
    ADD COLUMN IF NOT EXISTS decision_remark varchar(255);

UPDATE tbl_leave l SET leave_type_id = t.leave_type_id
  FROM tbl_leave_type t
 WHERE l.leave_type_id IS NULL AND t.code = l.leave_type;

-- Nothing may be left unmapped: a leave row without a type would break every balance figure.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM tbl_leave WHERE leave_type_id IS NULL) THEN
        RAISE EXCEPTION 'V6: leave rows with a type that is not in tbl_leave_type: %',
            (SELECT string_agg(DISTINCT coalesce(leave_type, '<null>'), ', ')
               FROM tbl_leave WHERE leave_type_id IS NULL);
    END IF;
END $$;

ALTER TABLE tbl_leave ALTER COLUMN leave_type_id SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_tbl_leave_type') THEN
        ALTER TABLE tbl_leave ADD CONSTRAINT fk_tbl_leave_type
            FOREIGN KEY (leave_type_id) REFERENCES tbl_leave_type (leave_type_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_tbl_leave_half_day_period') THEN
        ALTER TABLE tbl_leave ADD CONSTRAINT ck_tbl_leave_half_day_period
            CHECK (half_day_period IS NULL OR half_day_period IN ('MORNING', 'AFTERNOON'));
    END IF;
END $$;

-- Working days of every existing request: calendar days minus weekends minus public holidays.
UPDATE tbl_leave l
   SET day_portion = COALESCE((
        SELECT count(*)
          FROM generate_series(l.start_date, l.end_date, interval '1 day') AS g(day)
         WHERE extract(isodow FROM g.day) < 6
           AND NOT EXISTS (SELECT 1 FROM tbl_holiday h
                            WHERE extract(month FROM h.holiday_date) = extract(month FROM g.day)
                              AND extract(day   FROM h.holiday_date) = extract(day   FROM g.day))
       ), 0)
 WHERE l.day_portion IS NULL;

UPDATE tbl_leave SET submitted_on = start_date WHERE submitted_on IS NULL;
UPDATE tbl_leave SET decided_on = start_date
 WHERE decided_on IS NULL AND status IN ('APPROVED', 'REJECTED');

ALTER TABLE tbl_leave ALTER COLUMN day_portion SET NOT NULL;
ALTER TABLE tbl_leave ALTER COLUMN submitted_on SET NOT NULL;

CREATE INDEX IF NOT EXISTS ix_tbl_leave_employee_status ON tbl_leave (employee_id, status);

/* ------------------------------------------------------------------ 5. leave balances */

CREATE TABLE IF NOT EXISTS tbl_leave_balance (
    balance_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id       integer       NOT NULL,
    leave_type_id     integer       NOT NULL,
    balance_year      integer       NOT NULL,
    entitled_days     numeric(5, 1) NOT NULL DEFAULT 0,
    used_days         numeric(5, 1) NOT NULL DEFAULT 0,
    carried_over_days numeric(5, 1) NOT NULL DEFAULT 0,
    CONSTRAINT uq_tbl_leave_balance UNIQUE (employee_id, leave_type_id, balance_year),
    CONSTRAINT fk_tbl_leave_balance_employee FOREIGN KEY (employee_id) REFERENCES tbl_employee (employee_id),
    CONSTRAINT fk_tbl_leave_balance_type FOREIGN KEY (leave_type_id) REFERENCES tbl_leave_type (leave_type_id)
);

-- This year's entitlement for every active employee and every type that grants days.
INSERT INTO tbl_leave_balance (employee_id, leave_type_id, balance_year, entitled_days, used_days)
SELECT e.employee_id, t.leave_type_id, extract(year FROM CURRENT_DATE)::int, t.default_days_per_year, 0
  FROM tbl_employee e
 CROSS JOIN tbl_leave_type t
 WHERE e.status = 'ACTIVE' AND t.active AND t.default_days_per_year > 0
ON CONFLICT (employee_id, leave_type_id, balance_year) DO NOTHING;

-- Days already approved this year count as used.
UPDATE tbl_leave_balance b
   SET used_days = used.days
  FROM (SELECT l.employee_id, l.leave_type_id, sum(l.day_portion) AS days
          FROM tbl_leave l
         WHERE l.status = 'APPROVED'
           AND extract(year FROM l.start_date) = extract(year FROM CURRENT_DATE)
         GROUP BY l.employee_id, l.leave_type_id) AS used
 WHERE b.employee_id = used.employee_id
   AND b.leave_type_id = used.leave_type_id
   AND b.balance_year = extract(year FROM CURRENT_DATE)::int;
