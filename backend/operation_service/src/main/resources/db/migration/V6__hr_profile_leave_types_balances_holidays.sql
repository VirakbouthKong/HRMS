-- Module: real leave management + the full employee profile a HRMS is expected to hold.
--
--   1. tbl_employee gains the personal / contact / employment columns that were missing.
--      gender, address, phone_number and manager_id were already in the table (with data and a
--      reporting line in them) and are used as they are; only what is missing is added.
--   2. tbl_leave_type    leave is no longer a free-text string: types are configurable.
--   3. tbl_holiday       public holidays, so leave is counted in WORKING days.
--   4. tbl_leave_balance per employee, per type, per year -- what leave is actually left.
--   5. tbl_leave gains the columns a decision trail needs (working days, half day, who decided when).
--
-- The script stops with an error rather than guessing if the existing data is not as expected.

/* ------------------------------------------------------------------ 1. employee profile */

ALTER TABLE tbl_employee
    ADD COLUMN IF NOT EXISTS employee_code              varchar(20),
    -- the phone number lives in the existing phone_number column; no second column is added
    ADD COLUMN IF NOT EXISTS gender                     varchar(20),
    ADD COLUMN IF NOT EXISTS marital_status             varchar(20),
    ADD COLUMN IF NOT EXISTS national_id                varchar(40),
    ADD COLUMN IF NOT EXISTS address                    varchar(255),
    ADD COLUMN IF NOT EXISTS hire_date                  date,
    ADD COLUMN IF NOT EXISTS emergency_contact_name     varchar(120),
    ADD COLUMN IF NOT EXISTS emergency_contact_phone    varchar(30),
    ADD COLUMN IF NOT EXISTS emergency_contact_relation varchar(40),
    ADD COLUMN IF NOT EXISTS manager_id                 integer;

-- An employee reports to one other employee. Nobody may report to themselves.
--
-- The original data marks the top of the company by making that person their own manager.
-- The org chart finds its roots by "has no manager", so a self-reference would leave it with no
-- root at all; those rows are cleared, which is what "top of the company" means from here on.
UPDATE tbl_employee SET manager_id = NULL WHERE manager_id = employee_id;

DO $$
BEGIN
    -- The table may already have a foreign key on manager_id under another name; one is enough.
    IF NOT EXISTS (
        SELECT 1
          FROM pg_constraint c
          JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
         WHERE c.conrelid = 'tbl_employee'::regclass
           AND c.contype = 'f'
           AND a.attname = 'manager_id') THEN
        ALTER TABLE tbl_employee ADD CONSTRAINT fk_tbl_employee_manager
            FOREIGN KEY (manager_id) REFERENCES tbl_employee (employee_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_tbl_employee_manager_not_self') THEN
        ALTER TABLE tbl_employee ADD CONSTRAINT ck_tbl_employee_manager_not_self
            CHECK (manager_id IS NULL OR manager_id <> employee_id);
    END IF;
END $$;

-- Staff numbers: EMP0001, EMP0002, ... from the id the row already has.
UPDATE tbl_employee SET employee_code = 'EMP' || lpad(employee_id::text, 4, '0')
WHERE employee_code IS NULL;

-- Joined when their first job history row starts; employees without history start today.
UPDATE tbl_employee e SET hire_date = COALESCE(
        (SELECT min(h.started_date) FROM tbl_jobhistory h WHERE h.employee_id = e.employee_id),
        CURRENT_DATE)
WHERE e.hire_date IS NULL;

ALTER TABLE tbl_employee ALTER COLUMN employee_code SET NOT NULL;
ALTER TABLE tbl_employee ALTER COLUMN hire_date SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_tbl_employee_code') THEN
        ALTER TABLE tbl_employee ADD CONSTRAINT uq_tbl_employee_code UNIQUE (employee_code);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_tbl_employee_manager ON tbl_employee (manager_id);

-- A reporting line for anybody who does not have one yet: they report to the single
-- "... Manager" of their own department. A manager that is already set is never changed.
-- Departments without exactly one manager, and the managers themselves, are left unassigned --
-- HR sets those from the UI.
WITH one_manager AS (
    SELECT e.department_id, min(e.employee_id) AS manager_id
      FROM tbl_employee e
      JOIN tbl_job j ON j.job_id = e.job_id
     WHERE e.status = 'ACTIVE' AND trim(j.job_title) ILIKE '%manager%'
     GROUP BY e.department_id
    HAVING count(*) = 1
)
UPDATE tbl_employee e
   SET manager_id = m.manager_id
  FROM one_manager m
 WHERE e.department_id = m.department_id
   AND e.employee_id <> m.manager_id
   AND e.manager_id IS NULL;

/* ------------------------------------------------------------------ 2. leave types */

CREATE TABLE IF NOT EXISTS tbl_leave_type (
    leave_type_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  varchar(30)   NOT NULL,
    name                  varchar(100)  NOT NULL,
    paid                  boolean       NOT NULL DEFAULT true,
    -- how many days an employee is entitled to each year (0 = no entitlement, e.g. unpaid leave)
    default_days_per_year numeric(5, 1) NOT NULL DEFAULT 0,
    -- longest single request allowed, NULL = no limit
    max_consecutive_days  integer,
    requires_document     boolean       NOT NULL DEFAULT false,
    active                boolean       NOT NULL DEFAULT true,
    description           varchar(255),
    CONSTRAINT uq_tbl_leave_type_code UNIQUE (code)
);

INSERT INTO tbl_leave_type (code, name, paid, default_days_per_year, max_consecutive_days, requires_document, description)
VALUES ('ANNUAL',    'Annual leave',    true,  18, 15, false, 'Paid yearly entitlement.'),
       ('SICK',      'Sick leave',      true,  12, 10, true,  'A medical certificate is required from 3 days.'),
       ('UNPAID',    'Unpaid leave',    false,  0, 30, false, 'Deducted from salary; no entitlement.'),
       ('MATERNITY', 'Maternity leave', true,  90, 90, true,  'Paid, on production of a medical certificate.'),
       ('PATERNITY', 'Paternity leave', true,  10, 10, false, 'Paid, around the birth of a child.'),
       ('SPECIAL',   'Special leave',   true,   7,  5, false, 'Weddings, funerals and other approved occasions.')
ON CONFLICT (code) DO NOTHING;

-- The type on a leave row used to be free text, so the same thing was written several ways:
-- "SICK" and "Sick Leave", "Personal Leave". From here on the column holds the code of a type,
-- so the existing rows are rewritten the way a code is spelled: upper case, underscores for
-- spaces, and without a trailing "_LEAVE" ("Sick Leave" -> SICK, "Personal Leave" -> PERSONAL).
UPDATE tbl_leave
   SET leave_type = regexp_replace(
                        upper(regexp_replace(trim(leave_type), '[\s-]+', '_', 'g')),
                        '(.)_LEAVE$', '\1')
 WHERE leave_type IS NOT NULL AND trim(leave_type) <> '';

-- Any type already used in tbl_leave that is not in the list above becomes a type of its own,
-- so no historic leave row is left pointing at nothing. It grants no days until HR says so.
INSERT INTO tbl_leave_type (code, name, paid, default_days_per_year, description)
SELECT l.leave_type, initcap(replace(l.leave_type, '_', ' ')) || ' leave', true, 0,
       'Created by migration V6 from existing leave records.'
  FROM tbl_leave l
 WHERE l.leave_type IS NOT NULL AND trim(l.leave_type) <> ''
 GROUP BY l.leave_type
ON CONFLICT (code) DO NOTHING;

/* ------------------------------------------------------------------ 3. public holidays */

CREATE TABLE IF NOT EXISTS tbl_holiday (
    holiday_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holiday_date     date         NOT NULL,
    name             varchar(120) NOT NULL,
    -- true = the same day and month is a holiday every year (1 January, 9 November, ...)
    recurring_yearly boolean      NOT NULL DEFAULT false,
    description      varchar(255),
    CONSTRAINT uq_tbl_holiday_date UNIQUE (holiday_date)
);

