-- Module: performance management and training records.
--
--   tbl_review_cycle   a review period (half year, year) that everybody is appraised in
--   tbl_goal           what one employee is working towards in that cycle, with a weight
--   tbl_appraisal      the review itself: self rating, manager rating, final score
--   tbl_course         the training catalogue
--   tbl_enrolment      who is doing, or has done, which course
--
-- Ratings are 1 to 5. A goal carries a weight so the final score can be weighted by what
-- actually mattered, rather than being a flat average.

CREATE TABLE IF NOT EXISTS tbl_review_cycle (
    cycle_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(120) NOT NULL,
    period_start      date         NOT NULL,
    period_end        date         NOT NULL,
    -- DRAFT, OPEN, IN_REVIEW, CLOSED
    status            varchar(20)  NOT NULL DEFAULT 'DRAFT',
    self_review_due     date,
    manager_review_due  date,
    description         varchar(500),
    created_on          date       NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_tbl_review_cycle_name UNIQUE (name),
    CONSTRAINT ck_tbl_review_cycle_period CHECK (period_start <= period_end)
);

CREATE TABLE IF NOT EXISTS tbl_goal (
    goal_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id  integer       NOT NULL,
    cycle_id     integer       NOT NULL,
    title        varchar(200)  NOT NULL,
    description  varchar(2000),
    -- share of the final score this goal carries, in percent
    weight       numeric(5, 2) NOT NULL DEFAULT 0,
    -- 0 to 100
    progress     integer       NOT NULL DEFAULT 0,
    -- DRAFT, ACTIVE, ACHIEVED, MISSED, CANCELLED
    status       varchar(20)   NOT NULL DEFAULT 'ACTIVE',
    due_date     date,
    -- how the employee did on this goal, 1 to 5; set when the goal is closed off
    rating       integer,
    created_on   date          NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT ck_tbl_goal_weight CHECK (weight >= 0 AND weight <= 100),
    CONSTRAINT ck_tbl_goal_progress CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT ck_tbl_goal_rating CHECK (rating IS NULL OR (rating BETWEEN 1 AND 5)),
    CONSTRAINT fk_tbl_goal_employee FOREIGN KEY (employee_id) REFERENCES tbl_employee (employee_id),
    CONSTRAINT fk_tbl_goal_cycle FOREIGN KEY (cycle_id) REFERENCES tbl_review_cycle (cycle_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_goal_employee_cycle ON tbl_goal (employee_id, cycle_id);

CREATE TABLE IF NOT EXISTS tbl_appraisal (
    appraisal_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id         integer     NOT NULL,
    employee_id      integer     NOT NULL,
    -- normally the manager of the employee, captured here so a later move does not rewrite history
    reviewer_id      integer,
    -- NOT_STARTED, SELF_DONE, MANAGER_DONE, FINALISED
    status           varchar(20) NOT NULL DEFAULT 'NOT_STARTED',
    self_rating      integer,
    self_comment     varchar(2000),
    self_done_on     date,
    manager_rating   integer,
    manager_comment  varchar(2000),
    manager_done_on  date,
    -- the agreed outcome, 1.00 to 5.00; weighted by the goals when it is calculated
    final_score      numeric(4, 2),
    final_comment    varchar(2000),
    finalised_on     date,
    -- what happens next: PROMOTION, SALARY_REVIEW, TRAINING, NONE, PERFORMANCE_PLAN
    outcome          varchar(20),
    CONSTRAINT uq_tbl_appraisal_per_cycle UNIQUE (cycle_id, employee_id),
    CONSTRAINT ck_tbl_appraisal_self CHECK (self_rating IS NULL OR (self_rating BETWEEN 1 AND 5)),
    CONSTRAINT ck_tbl_appraisal_manager CHECK (manager_rating IS NULL OR (manager_rating BETWEEN 1 AND 5)),
    CONSTRAINT ck_tbl_appraisal_final CHECK (final_score IS NULL OR (final_score BETWEEN 1 AND 5)),
    CONSTRAINT fk_tbl_appraisal_cycle FOREIGN KEY (cycle_id) REFERENCES tbl_review_cycle (cycle_id),
    CONSTRAINT fk_tbl_appraisal_employee FOREIGN KEY (employee_id) REFERENCES tbl_employee (employee_id),
    CONSTRAINT fk_tbl_appraisal_reviewer FOREIGN KEY (reviewer_id) REFERENCES tbl_employee (employee_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_appraisal_employee ON tbl_appraisal (employee_id);
CREATE INDEX IF NOT EXISTS ix_tbl_appraisal_reviewer ON tbl_appraisal (reviewer_id);

/* ------------------------------------------------------------------ training */

CREATE TABLE IF NOT EXISTS tbl_course (
    course_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        varchar(30)   NOT NULL,
    title       varchar(200)  NOT NULL,
    provider    varchar(150),
    -- CLASSROOM, ONLINE, WORKSHOP, CERTIFICATION, ON_THE_JOB
    delivery    varchar(20)   NOT NULL DEFAULT 'ONLINE',
    hours       numeric(5, 1) NOT NULL DEFAULT 0,
    cost        numeric(10, 2),
    mandatory   boolean       NOT NULL DEFAULT false,
    active      boolean       NOT NULL DEFAULT true,
    description varchar(1000),
    CONSTRAINT uq_tbl_course_code UNIQUE (code),
    CONSTRAINT ck_tbl_course_hours CHECK (hours >= 0)
);

CREATE TABLE IF NOT EXISTS tbl_enrolment (
    enrolment_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   integer     NOT NULL,
    course_id     integer     NOT NULL,
    -- ENROLLED, IN_PROGRESS, COMPLETED, FAILED, CANCELLED
    status        varchar(20) NOT NULL DEFAULT 'ENROLLED',
    enrolled_on   date        NOT NULL DEFAULT CURRENT_DATE,
    started_on    date,
    completed_on  date,
    -- result out of 100, where the course is graded
    score         integer,
    certificate_no varchar(80),
    -- certifications expire; this is what the renewal report looks at
    expires_on    date,
    notes         varchar(500),
    CONSTRAINT ck_tbl_enrolment_score CHECK (score IS NULL OR (score BETWEEN 0 AND 100)),
    CONSTRAINT fk_tbl_enrolment_employee FOREIGN KEY (employee_id) REFERENCES tbl_employee (employee_id),
    CONSTRAINT fk_tbl_enrolment_course FOREIGN KEY (course_id) REFERENCES tbl_course (course_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_enrolment_employee ON tbl_enrolment (employee_id);
CREATE INDEX IF NOT EXISTS ix_tbl_enrolment_course ON tbl_enrolment (course_id);

