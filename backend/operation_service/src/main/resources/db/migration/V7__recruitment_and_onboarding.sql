-- Module: recruitment (applicant tracking) and the onboarding / offboarding checklist.
--
--   tbl_requisition      an approved opening: which job, in which department, how many people
--   tbl_candidate        somebody applying for one requisition, and where they are in the pipeline
--   tbl_interview        one interview round for a candidate, with a score and a recommendation
--   tbl_checklist_task   what has to happen when somebody joins or leaves
--
-- A candidate who is hired is turned into a row in tbl_employee by the API, which is why
-- tbl_candidate keeps a nullable hired_employee_id pointing back at the person they became.

CREATE TABLE IF NOT EXISTS tbl_requisition (
    requisition_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference         varchar(20)  NOT NULL,
    title             varchar(150) NOT NULL,
    department_id     integer      NOT NULL,
    -- the job title the new hire will get; NULL while the opening is still being written
    job_id            integer,
    headcount         integer      NOT NULL DEFAULT 1,
    -- DRAFT, OPEN, ON_HOLD, FILLED, CLOSED
    status            varchar(20)  NOT NULL DEFAULT 'DRAFT',
    employment_type   varchar(20)  NOT NULL DEFAULT 'FULL_TIME',
    location          varchar(120),
    min_salary        numeric(10, 2),
    max_salary        numeric(10, 2),
    opened_on         date,
    target_start_date date,
    closed_on         date,
    description       varchar(2000),
    -- who raised it; NULL if that employee has since been removed
    raised_by         integer,
    created_on        date         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_tbl_requisition_reference UNIQUE (reference),
    CONSTRAINT ck_tbl_requisition_headcount CHECK (headcount >= 1),
    CONSTRAINT ck_tbl_requisition_salary CHECK (min_salary IS NULL OR max_salary IS NULL OR min_salary <= max_salary),
    CONSTRAINT fk_tbl_requisition_department FOREIGN KEY (department_id) REFERENCES tbl_department (department_id),
    CONSTRAINT fk_tbl_requisition_job FOREIGN KEY (job_id) REFERENCES tbl_job (job_id),
    CONSTRAINT fk_tbl_requisition_raised_by FOREIGN KEY (raised_by) REFERENCES tbl_employee (employee_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_requisition_status ON tbl_requisition (status);

CREATE TABLE IF NOT EXISTS tbl_candidate (
    candidate_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requisition_id     integer      NOT NULL,
    full_name          varchar(150) NOT NULL,
    email              varchar(150) NOT NULL,
    phone              varchar(30),
    -- APPLIED, SCREENING, INTERVIEW, OFFER, HIRED, REJECTED, WITHDRAWN
    stage              varchar(20)  NOT NULL DEFAULT 'APPLIED',
    -- WEBSITE, REFERRAL, AGENCY, JOB_BOARD, WALK_IN, OTHER
    source             varchar(20)  NOT NULL DEFAULT 'OTHER',
    applied_on         date         NOT NULL DEFAULT CURRENT_DATE,
    expected_salary    numeric(10, 2),
    offered_salary     numeric(10, 2),
    years_experience   integer,
    resume_url         varchar(500),
    notes              varchar(2000),
    -- filled in when the stage becomes HIRED and the employee record is created
    hired_employee_id  integer,
    stage_changed_on   date,
    rejection_reason   varchar(255),
    CONSTRAINT uq_tbl_candidate_per_requisition UNIQUE (requisition_id, email),
    CONSTRAINT fk_tbl_candidate_requisition FOREIGN KEY (requisition_id) REFERENCES tbl_requisition (requisition_id),
    CONSTRAINT fk_tbl_candidate_employee FOREIGN KEY (hired_employee_id) REFERENCES tbl_employee (employee_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_candidate_stage ON tbl_candidate (stage);
CREATE INDEX IF NOT EXISTS ix_tbl_candidate_requisition ON tbl_candidate (requisition_id);

CREATE TABLE IF NOT EXISTS tbl_interview (
    interview_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id   integer      NOT NULL,
    round_number   integer      NOT NULL DEFAULT 1,
    -- PHONE_SCREEN, TECHNICAL, PANEL, HR, FINAL
    round_type     varchar(20)  NOT NULL DEFAULT 'TECHNICAL',
    scheduled_at   timestamp    NOT NULL,
    -- the employee running it; NULL if an external interviewer
    interviewer_id integer,
    -- SCHEDULED, COMPLETED, NO_SHOW, CANCELLED
    status         varchar(20)  NOT NULL DEFAULT 'SCHEDULED',
    -- 1 (poor) to 5 (excellent), filled in afterwards
    score          integer,
    -- STRONG_YES, YES, NEUTRAL, NO, STRONG_NO
    recommendation varchar(20),
    notes          varchar(2000),
    CONSTRAINT ck_tbl_interview_round CHECK (round_number >= 1),
    CONSTRAINT ck_tbl_interview_score CHECK (score IS NULL OR (score BETWEEN 1 AND 5)),
    CONSTRAINT fk_tbl_interview_candidate FOREIGN KEY (candidate_id) REFERENCES tbl_candidate (candidate_id),
    CONSTRAINT fk_tbl_interview_interviewer FOREIGN KEY (interviewer_id) REFERENCES tbl_employee (employee_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_interview_candidate ON tbl_interview (candidate_id);

-- One checklist covers both directions: joining (ONBOARDING) and leaving (OFFBOARDING).
CREATE TABLE IF NOT EXISTS tbl_checklist_task (
    task_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id integer      NOT NULL,
    -- ONBOARDING or OFFBOARDING
    kind        varchar(20)  NOT NULL DEFAULT 'ONBOARDING',
    title       varchar(150) NOT NULL,
    -- which team has to do it: HR, IT, FINANCE, MANAGER, EMPLOYEE
    owner_team  varchar(20)  NOT NULL DEFAULT 'HR',
    due_date    date,
    done        boolean      NOT NULL DEFAULT false,
    done_on     date,
    -- the employee who ticked it off
    done_by     integer,
    sort_order  integer      NOT NULL DEFAULT 0,
    notes       varchar(500),
    CONSTRAINT fk_tbl_checklist_employee FOREIGN KEY (employee_id) REFERENCES tbl_employee (employee_id),
    CONSTRAINT fk_tbl_checklist_done_by FOREIGN KEY (done_by) REFERENCES tbl_employee (employee_id)
);

CREATE INDEX IF NOT EXISTS ix_tbl_checklist_employee ON tbl_checklist_task (employee_id, kind);
