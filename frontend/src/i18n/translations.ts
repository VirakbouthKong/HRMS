export function getMonthLabel(monthIndex: number, year: number, lang: Language, short = false): string {
  const khMonths = [
    'មករា', 'កុម្ភៈ', 'មីនា', 'មេសា', 'ឧសភា', 'មិថុនា',
    'កក្កដា', 'សីហា', 'កញ្ញា', 'តុលា', 'វិច្ឆិកា', 'ធ្នូ',
  ];
  const enMonthsFull = [
    'January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December',
  ];
  const enMonthsShort = [
    'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
    'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec',
  ];
  if (lang === 'kh') {
    return `${khMonths[monthIndex]} ${year}`;
  }
  return `${short ? enMonthsShort[monthIndex] : enMonthsFull[monthIndex]} ${year}`;
}
